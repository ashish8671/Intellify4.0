import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export const generateInspectionReport = ({
  inspection,
  statistics,
  detections,
}) => {
  try {
    const doc = new jsPDF();

    // ==========================
    // Header
    // ==========================
    doc.setFontSize(22);
    doc.setTextColor(0, 102, 204);
    doc.text("Neuro-Twin Mesh", 15, 18);

    doc.setFontSize(12);
    doc.setTextColor(80);
    doc.text("AI Structural Health Monitoring", 15, 26);

    doc.line(15, 30, 195, 30);

    // ==========================
    // Inspection Details
    // ==========================
    doc.setFontSize(16);
    doc.setTextColor(0);
    doc.text("Inspection Details", 15, 42);

    doc.setFontSize(11);

    doc.text(
      `Inspector : ${inspection?.inspector || "N/A"}`,
      15,
      52
    );

    doc.text(
      `Building : ${inspection?.building || "N/A"}`,
      15,
      60
    );

    doc.text(
      `Location : ${inspection?.location || "N/A"}`,
      15,
      68
    );

    doc.text(
      `Date : ${inspection?.date || "N/A"}`,
      15,
      76
    );

    // ==========================
    // Summary
    // ==========================

    doc.setFontSize(16);
    doc.text("Summary", 15, 92);

    doc.setFontSize(11);

    doc.text(
      `Total Defects : ${statistics?.total ?? 0}`,
      15,
      102
    );

    doc.text(
      `High Risk : ${statistics?.high ?? 0}`,
      15,
      110
    );

    doc.text(
      `Medium Risk : ${statistics?.medium ?? 0}`,
      15,
      118
    );

    doc.text(
      `Low Risk : ${statistics?.low ?? 0}`,
      15,
      126
    );

    // ==========================
    // Table
    // ==========================

    autoTable(doc, {
      startY: 136,
      head: [["ID", "Defect", "Severity", "Confidence"]],
      body:
        detections?.map((item) => [
          item.id,
          item.label,
          item.severity,
          `${item.confidence}%`,
        ]) || [],
    });

    const finalY =
      doc.lastAutoTable?.finalY
        ? doc.lastAutoTable.finalY + 15
        : 220;

    doc.setFontSize(12);

    doc.text(
      "Generated by Neuro-Twin Mesh",
      15,
      finalY
    );

    doc.setFontSize(10);

    doc.text(
      "MIT ADT University | Intellify 4.0",
      15,
      finalY + 8
    );

    doc.save("Inspection_Report.pdf");
  } catch (error) {
    console.error(error);
    alert("Unable to generate PDF");
  }
};